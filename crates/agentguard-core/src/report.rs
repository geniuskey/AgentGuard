//! Markdown policy report generation (req §16.4 Policy Report — could-have).

use crate::effective::EffectivePolicy;
use crate::risk::RiskScore;

/// Report explicit rules by tool. The legacy risk argument is not a security grade.
pub fn markdown(
    project_name: &str,
    profile: Option<&str>,
    _risk: &RiskScore,
    effective: &[EffectivePolicy],
) -> String {
    let mut out = String::new();
    out.push_str(&format!("# Agent Guard Policy Report — {project_name}\n\n"));
    out.push_str(&format!(
        "- Legacy profile label: **{}** (does not define the current permissions)\n\n",
        profile.unwrap_or("—")
    ));
    out.push_str("This report compares explicit rules only. It is not a security grade or a prediction of runtime approval. Runtime modes, trust, CLI flags, hooks and symlinks are not evaluated. No matching rule does not imply an Ask prompt.\n\n");
    for e in effective {
        out.push_str(&format!(
            "- {} `{}`: {}{}\n",
            e.tool.as_str(),
            e.path,
            e.effective
                .map(|p| format!("{p:?}"))
                .unwrap_or_else(|| "No conclusion".into()),
            if e.incomplete {
                " (unsupported pattern or missing context)"
            } else {
                ""
            }
        ));
    }
    out.push('\n');
    out.push_str("---\n_Generated by Agent Guard._\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::effective::EffectivePolicy;
    use crate::model::{Policy, Scope};
    use crate::risk::RiskScore;

    #[test]
    fn renders_sections() {
        let eff = vec![
            EffectivePolicy {
                path: "src".into(),
                effective: Some(Policy::Allow),
                tool: crate::Tool::Read,
                incomplete: false,
                source_scope: Some(Scope::Project),
                explicit: true,
                conflict: false,
            },
            EffectivePolicy {
                path: "secrets".into(),
                effective: Some(Policy::Deny),
                tool: crate::Tool::Read,
                incomplete: false,
                source_scope: Some(Scope::Project),
                explicit: true,
                conflict: false,
            },
        ];
        let md = markdown(
            "proj",
            Some("Conservative"),
            &RiskScore {
                score: 80,
                level: crate::model::RiskLevel::High,
            },
            &eff,
        );
        assert!(md.contains("# Agent Guard Policy Report — proj"));
        assert!(md.contains("Read `src`: Allow"));
        assert!(md.contains("Read `secrets`: Deny"));
        assert!(!md.contains("Risk score"));
        assert!(md.contains("Conservative"));
    }
}
